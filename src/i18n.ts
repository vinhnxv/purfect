// Slash commands of the review chat box, in the order they are suggested.
export const COMMAND_NAMES = ['approve', 'edit', 'improve', 'history', 'undo', 'redo', 'back', 'config', 'quit'] as const;
export type CommandName = (typeof COMMAND_NAMES)[number];

// Every string the interface shows. The model's own output (explanations, tips) is not here:
// the rewrite prompt asks for it in the display language directly.
export type Messages = {
	commands: Record<CommandName, string>;
	draft: string;
	composeTitle: string;
	version: (n: number, total: number, label: string) => string;
	labels: {first: string; again: string; improve: string; manual: string};
	working: {rewrite: (language: string) => string; refine: string; improve: string};
	error: (reason: string) => string;
	kept: (reason: string) => string;
	meaning: string;
	structure: string;
	promptClear: string;
	alreadyClear: string;
	placeholders: string;
	unknownCommand: (name: string) => string;
	unavailable: (name: string) => string;
	approveHint: string;
	refineHint: string;
	commandHint: string;
	suggestKeys: string;
	historyTitle: string;
	inUse: string;
	editTitle: string;
	settings: {
		title: string;
		pick: (label: string) => string;
		text: (label: string) => string;
		labels: Record<SettingKey, string>;
		unset: string;
		env: (name: string) => string;
		saved: (label: string, value: string) => string;
		redo: string;
		path: (path: string) => string;
	};
};

